export function getMccCategory(mcc: number): string {
  for (const [category, ranges] of Object.entries(MCC_CATEGORIES)) {
    for (const [from, to] of ranges) {
      if (mcc >= from && mcc <= to) {
        return category;
      }
    }
  }
  return "Інше";
}

